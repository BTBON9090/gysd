// Isolated in-memory front-end business checks; no browser storage is touched.
import assert from 'node:assert/strict'
import { createServer } from 'vite'
import { createPinia, setActivePinia } from 'pinia'
const storage = new Map()
globalThis.localStorage = { getItem: k => storage.get(k) ?? null, setItem: (k,v) => storage.set(k,String(v)), removeItem: k => storage.delete(k) }
globalThis.window = { setInterval: () => 0 }
const vite = await createServer({ server: { middlewareMode: true }, appType: 'custom' })
try {
  const { useCommerceStore } = await vite.ssrLoadModule('/src/stores/commerce.ts')
  setActivePinia(createPinia())
  const c = useCommerceStore()
  const fresh = () => { c.seed(); return c.data.orders.find(o => o.id === 'DEMO-ORDER-MULTI-001') }
  let o = fresh()
  assert.equal(o.stages.reduce((n,s) => n+s.amount,0), o.amount)
  assert.equal(o.stages.reduce((n,s) => n+s.paid,0), o.paid)
  assert.equal(o.stages.reduce((n,s) => n+s.refunded,0), o.refunded)
  assert.equal(c.requestAcceptance(o.id,['proof.pdf'],'test','phase-2'),false, 'refund blocks fulfillment')
  assert.equal(c.payOrderStage(o.id),false, 'refund blocks next payment')
  let r = c.activeRefund(o.id)
  assert.equal(c.decideRefund(r.id,'agree',8000,'continue',''),false,'changed amount needs client confirmation')
  assert.equal(c.decideRefund(r.id,'change',8000,'continue',''),false,'change requires reason')
  assert.equal(c.decideRefund(r.id,'change',8000,'continue','双方调整范围'),true)
  assert.equal(r.status,'client_confirm')
  assert.equal(o.refunded,2400,'proposal must not move money')
  assert.equal(c.finalizeRefund(r.id,false),true)
  assert.equal(r.status,'pending')
  assert.equal(c.decideRefund(r.id,'change',8000,'continue','补充调整方案'),true)
  assert.equal(c.finalizeRefund(r.id),true)
  assert.equal(o.refunded,10400)
  assert.equal(o.stages[1].refunded,8000)
  assert.equal(c.finalizeRefund(r.id),false,'duplicate callback must be idempotent')
  assert.equal(c.requestAcceptance(o.id,['proof.pdf'],'wrong phase','phase-3'),false)
  assert.equal(c.requestAcceptance(o.id,['proof.pdf'],'phase 2','phase-2'),true)
  assert.equal(c.concludeAcceptance(o.id,false),true)
  assert.equal(o.stages[1].status,'rejected')
  assert.equal(c.requestAcceptance(o.id,['proof-v2.pdf'],'fixed','phase-2'),true)
  assert.equal(c.concludeAcceptance(o.id,true),true)
  assert.equal(o.status,'in_service','phase 2 acceptance must not finish all phases')
  assert.equal(c.requestAcceptance(o.id,['proof.pdf'],'unpaid','phase-3'),false)
  assert.equal(c.payOrderStage(o.id),true)
  assert.equal(o.paid,128000)
  assert.equal(c.payOrderStage(o.id),false,'repeat payment must not double count')
  assert.equal(c.requestAcceptance(o.id,['handover.pdf'],'phase 3','phase-3'),true)
  assert.equal(c.concludeAcceptance(o.id,true),true)
  assert.equal(o.status,'completed')
  assert.ok(o.afterSaleEnd)
  assert.equal(c.invoiceable(o),117600)
  o = fresh(); r = c.activeRefund(o.id)
  assert.equal(c.decideRefund(r.id,'agree',8500,'close','终止项目'),true)
  assert.equal(o.status,'cancelled')
  assert.equal(c.requestAcceptance(o.id,['file.pdf'],'','phase-2'),false)
  assert.equal(c.payOrderStage(o.id),false)
  assert.equal(c.invoiceable(o),78700,'closed orders retain invoiceable net receipts')
  o = fresh(); r = c.activeRefund(o.id)
  assert.equal(c.decideRefund(r.id,'reject',8500,'continue','范围内工作已完成'),true)
  assert.ok(c.activeRefund(o.id),'rejected refund blocks until cancelled or reapplied')
  assert.equal(c.createRefund(o.id,60000,'超本期余额','phase-2'),false)
  assert.equal(c.createRefund(o.id,6000,'重新申请','phase-2'),true)
  const next = c.activeRefund(o.id)
  assert.notEqual(next.id,r.id)
  assert.equal(c.decideRefund(next.id,'agree',6000,'continue',''),true)
  assert.equal(c.activeRefund(o.id),undefined,'superseded rejected request must not block')
  o = fresh(); r = c.activeRefund(o.id)
  c.cancelRefund(r.id)
  assert.equal(c.issueInvoice('customer',[o.id],'INV-TEST','invoice.pdf','test','test@example.com'),true)
  assert.equal(c.createRefund(o.id,500,'invoice locked','phase-2'),false)
  c.returnInvoice(c.data.invoices[0].id)
  assert.equal(c.createRefund(o.id,500,'invoice returned','phase-2'),true)
  o = fresh(); r = c.activeRefund(o.id); c.cancelRefund(r.id)
  o.settlement='settled'
  assert.equal(c.createRefund(o.id,500,'already settled','phase-2'),false)
  o = fresh(); r = c.activeRefund(o.id); c.cancelRefund(r.id)
  assert.equal(c.createRefund(o.id,5000,'整单退款'),true)
  assert.equal(c.decideRefund(c.activeRefund(o.id).id,'agree',5000,'continue',''),true)
  assert.equal(o.stages.reduce((n,s)=>n+s.refunded,0),o.refunded,'whole-order refunds must reconcile with stage ledger')
  c.seed()
  const single = c.data.orders.find(o=>o.id==='DEMO-ORDER-002')
  c.cancelRefund(c.activeRefund(single.id).id)
  assert.equal(c.requestAcceptance(single.id,['delivery.pdf'],'single'),true)
  assert.equal(c.concludeAcceptance(single.id,true),true)
  assert.equal(single.status,'completed','legacy single stage remains compatible')
  console.log('PASS: stage balances, refund guards, client negotiation, idempotency, staged acceptance/payment, closing, invoicing and single-stage compatibility')
} finally { await vite.close() }
